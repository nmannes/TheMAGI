#!/usr/bin/env bash
# Deploy the headless hit-review pipeline to the clyde Linux server.
#
# Usage:
#   ./scripts/deploy-clyde.sh [--assets] [--replays] [--skip-install] [--skip-smoke]
#
# What it does:
#   1. rsyncs the source (excluding node_modules, .git, site, screenshots, renders)
#   2. optionally copies the Melee ISO and Slippi Playback AppImage, then
#      extracts the AppImage (no libfuse2 needed)
#   3. optionally copies ~/Slippi replays, keeping existing server files
#   4. runs npm ci on the server
#   5. writes ~/clippi/key.env if missing (never overwrites it)
#   6. runs a chronological query against one replay as a smoke test
#
# Safe to re-run. Override paths with MAGI_TARGET, MELEE_ISO,
# SLIPPI_PLAYBACK_APPIMAGE, REPLAY_DIR, CLYDE_HOST, CLYDE_DIR or CLYDE_ASSETS.
set -euo pipefail

ROOT_DIR=$(cd "$(dirname "$(realpath "${BASH_SOURCE[0]}")")/.." && pwd)
HOST="${CLYDE_HOST:-clyde}"
REMOTE_DIR="${CLYDE_DIR:-clippi}"
REMOTE_ASSETS="${CLYDE_ASSETS:-clippi-assets}"
LOCAL_ISO="${MELEE_ISO:-$HOME/Desktop/smash.iso}"
LOCAL_PLAYBACK="${SLIPPI_PLAYBACK_APPIMAGE:-$HOME/.config/Slippi Launcher/playback/Slippi_Playback-x86_64.AppImage}"
LOCAL_REPLAYS="${REPLAY_DIR:-$HOME/Slippi}"
TARGET="${MAGI_TARGET:-POOK#392}"

COPY_ASSETS=0
COPY_REPLAYS=0
RUN_INSTALL=1
RUN_SMOKE=1

while (($#)); do
  case "$1" in
    --assets) COPY_ASSETS=1 ;;
    --replays) COPY_REPLAYS=1 ;;
    --skip-install) RUN_INSTALL=0 ;;
    --skip-smoke) RUN_SMOKE=0 ;;
    --host)
      HOST="${2:?--host needs a value}"
      shift
      ;;
    -h | --help)
      sed -n '2,22p' "$0"
      exit 0
      ;;
    *)
      echo "unknown option: $1" >&2
      exit 2
      ;;
  esac
  shift
done

log() {
  printf '[deploy] %s\n' "$*"
}

remote() {
  ssh -o BatchMode=yes -o ConnectTimeout=10 "$HOST" "$@"
}

log "syncing source to $HOST:~/$REMOTE_DIR (small tree: no node_modules/.git/site/screenshots/renders)"
rsync -az --info=progress2 \
  --exclude node_modules \
  --exclude .git \
  --exclude site \
  --exclude screenshots \
  --exclude renders \
  --exclude dist \
  --exclude .vite \
  --exclude key.env \
  --exclude '*.log' \
  "$ROOT_DIR/" "$HOST:$REMOTE_DIR/"

remote "mkdir -p \"\$HOME/$REMOTE_ASSETS\""

if ((COPY_ASSETS)); then
  [[ -f "$LOCAL_ISO" ]] || {
    echo "Melee ISO not found: $LOCAL_ISO (set MELEE_ISO)" >&2
    exit 1
  }
  [[ -f "$LOCAL_PLAYBACK" ]] || {
    echo "Slippi Playback AppImage not found: $LOCAL_PLAYBACK (set SLIPPI_PLAYBACK_APPIMAGE)" >&2
    exit 1
  }

  log "copying Melee ISO ($(du -h "$LOCAL_ISO" | cut -f1)) to $HOST:~/$REMOTE_ASSETS/smash.iso"
  rsync -az --partial --info=progress2 "$LOCAL_ISO" "$HOST:$REMOTE_ASSETS/smash.iso"

  log "copying Slippi Playback AppImage to $HOST:~/$REMOTE_ASSETS/"
  rsync -az --partial --info=progress2 "$LOCAL_PLAYBACK" "$HOST:$REMOTE_ASSETS/Slippi_Playback-x86_64.AppImage"

  log "extracting Slippi Playback on $HOST (avoids the missing libfuse2)"
  remote 'bash -s' <<REMOTE
set -euo pipefail
assets="\$HOME/$REMOTE_ASSETS"
appimage="\$assets/Slippi_Playback-x86_64.AppImage"
appdir="\$assets/slippi-playback"
if [ -x "\$appdir/squashfs-root/AppRun" ]; then
  echo "playback already extracted at \$appdir/squashfs-root/AppRun"
  exit 0
fi
chmod +x "\$appimage"
mkdir -p "\$appdir"
cd "\$appdir"
"\$appimage" --appimage-extract >/dev/null
echo "extracted to \$appdir/squashfs-root/AppRun"
REMOTE
fi

if ((COPY_REPLAYS)); then
  [[ -d "$LOCAL_REPLAYS" ]] || {
    echo "replay folder not found: $LOCAL_REPLAYS (set REPLAY_DIR)" >&2
    exit 1
  }
  log "copying replays from $LOCAL_REPLAYS to $HOST:~/Slippi (existing files kept)"
  remote 'mkdir -p "$HOME/Slippi"'
  rsync -az --ignore-existing --info=progress2 "$LOCAL_REPLAYS/" "$HOST:Slippi/"
fi

if ((RUN_INSTALL)); then
  log "installing Node dependencies on $HOST with npm ci"
  remote "cd \"\$HOME/$REMOTE_DIR\" && npm ci"
fi

log "preparing key.env (existing file is left untouched)"
remote 'bash -s' <<REMOTE
set -euo pipefail
key_env="\$HOME/$REMOTE_DIR/key.env"
if [ -f "\$key_env" ]; then
  echo "key.env already exists; leaving it untouched"
  exit 0
fi
node_bin=\$(dirname "\$(command -v node)")
cat > "\$key_env" <<EOF
# Generated by scripts/deploy-clyde.sh. Keep this file private.
MAGI_TARGET='$TARGET'
SLIPPI_PLAYBACK=\$HOME/$REMOTE_ASSETS/slippi-playback/squashfs-root/AppRun
MELEE_ISO=\$HOME/$REMOTE_ASSETS/smash.iso
REPLAY_DIR=\$HOME/Slippi
HIT_REVIEW_PATH=\$node_bin
# Fill these in to enable Telegram delivery:
# TELEGRAM_BOT_TOKEN=...
# TELEGRAM_CHAT_ID=...
EOF
chmod 600 "\$key_env"
echo "wrote \$key_env"
REMOTE

if ((RUN_SMOKE)); then
  log "querying one replay in chronological mode on $HOST"
  remote 'bash -s' <<REMOTE
set -euo pipefail
cd "\$HOME/$REMOTE_DIR"
set -a
. ./key.env
set +a
replay=\$(find "\$REPLAY_DIR" -type f -name '*.slp' -print -quit)
if [ -z "\$replay" ]; then
  echo "no replay found under \$REPLAY_DIR; copy replays with --replays" >&2
  exit 1
fi
echo "replay: \$replay"
# Throwaway cursor so the smoke query always selects from the start and never
# disturbs the production cursor/cache.
cursor="\${TMPDIR:-/tmp}/hit-review-smoke-\$\$.json"
rm -f "\$cursor"
npx --no-install tsx src/hit-review-cli.ts \
  --replay "\$replay" --target "\$MAGI_TARGET" \
  --chronological --cursor "\$cursor" --limit 2 --json
rm -f "\$cursor"
REMOTE
fi

log "done"
